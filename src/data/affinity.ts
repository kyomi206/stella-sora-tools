export function getCumulativeExp(level: number): number {
  if (level <= 1) return 0;
  if (level >= 100) {
    return AFFINITY_EXP_TABLE[AFFINITY_EXP_TABLE.length - 1].totalExpToLevel;
  }
  const entry = AFFINITY_EXP_TABLE.find(e => e.level === level - 1);
  return entry ? entry.totalExpToLevel : 0;
}

export function calculateAffinityReq(
  currentLevel: number,
  currentExp: number,
  targetLevel: number
) {
  const currentTotal = getCumulativeExp(currentLevel) + Math.max(0, currentExp);
  const targetTotal = getCumulativeExp(targetLevel);
  const neededExp = Math.max(0, targetTotal - currentTotal);

  return {
    currentTotal,
    targetTotal,
    neededExp,
    isAlreadyReached: currentTotal >= targetTotal,
  };
}

export function optimizeGifts(
  neededExp: number,
  isFavorite: boolean = false,
  isDateBonus: boolean = false
) {
  // Loved gift gives +50% bonus (1.5x)
  // Date bonus gives 2x
  const multiplier = (isFavorite ? 1.5 : 1) * (isDateBonus ? 2 : 1);
  const exqExp = Math.round(2000 * multiplier);
  const rareExp = Math.round(500 * multiplier);
  const comExp = Math.round(150 * multiplier);

  let remaining = neededExp;
  const exquisite = Math.floor(remaining / exqExp);
  remaining %= exqExp;

  const rare = Math.floor(remaining / rareExp);
  remaining %= rareExp;

  const common = Math.ceil(remaining / comExp);

  const totalExpProvided = (exquisite * exqExp) + (rare * rareExp) + (common * comExp);
  const overflowExp = Math.max(0, totalExpProvided - neededExp);

  return {
    multiplier,
    exquisite,
    rare,
    common,
    totalExpProvided,
    overflowExp,
  };
}
