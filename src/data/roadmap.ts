export function getTrekkerAvatarUrl(characterId?: number, imageUrl?: string): string {
  if (imageUrl) return imageUrl;
  if (!characterId) return '';
  return `https://raw.githubusercontent.com/AutumnVN/ssassets/refs/heads/main/export/assets/assetbundles/icon/head/head_${characterId}01_L.webp`;
}

